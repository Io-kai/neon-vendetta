const GLYPH_W = 5;
const GLYPH_H = 7;
export const TEXT_ADVANCE = 6;

export function bakeFont(scene: Phaser.Scene): void {
  for (const [ch, rows] of Object.entries(GLYPHS)) {
    const key = `glyph_${ch === ' ' ? 'sp' : ch}`;
    if (scene.textures.exists(key)) continue;
    const tex = scene.textures.createCanvas(key, GLYPH_W, GLYPH_H);
    if (!tex) continue;
    const ctx = tex.getContext();
    ctx.fillStyle = '#ffffff';
    for (let y = 0; y < GLYPH_H; y++) {
      for (let x = 0; x < GLYPH_W; x++) {
        if (rows[y] & (1 << (GLYPH_W - 1 - x))) ctx.fillRect(x, y, 1, 1);
      }
    }
    tex.refresh();
  }
}

export function textWidth(text: string, scale: number): number {
  return text.length * TEXT_ADVANCE * scale - scale;
}

// Render a string into a cached texture (glyphs tinted with `color`).
export function bakeText(
  scene: Phaser.Scene,
  text: string,
  color = '#ffffff',
  scale = 1,
  shadow = false
): string {
  const key = `text_${text}_${color}_${scale}_${shadow ? 1 : 0}`;
  if (scene.textures.exists(key)) return key;

  const w = Math.max(1, textWidth(text, scale));
  const h = GLYPH_H * scale + (shadow ? scale : 0);
  const tex = scene.textures.createCanvas(key, w + (shadow ? scale : 0), h);
  if (!tex) return key;
  const ctx = tex.getContext();

  const drawPass = (dx: number, dy: number, fill: string) => {
    ctx.fillStyle = fill;
    for (let i = 0; i < text.length; i++) {
      const ch = text[i].toUpperCase();
      const rows = GLYPHS[ch] ?? GLYPHS[' '];
      const ox = dx + i * TEXT_ADVANCE * scale;
      for (let y = 0; y < GLYPH_H; y++) {
        for (let x = 0; x < GLYPH_W; x++) {
          if (rows[y] & (1 << (GLYPH_W - 1 - x))) {
            ctx.fillRect(ox + x * scale, dy + y * scale, scale, scale);
          }
        }
      }
    }
  };

  if (shadow) drawPass(scale, scale, '#08080f');
  drawPass(0, 0, color);
  tex.refresh();
  return key;
}

// Convenience: add a baked-text image to the scene.
export function addText(
  scene: Phaser.Scene,
  x: number,
  y: number,
  text: string,
  color = '#ffffff',
  scale = 1,
  shadow = true
): Phaser.GameObjects.Image {
  const key = bakeText(scene, text, color, scale, shadow);
  return scene.add.image(x, y, key).setOrigin(0, 0);
}

export function addTextCentered(
  scene: Phaser.Scene,
  cx: number,
  y: number,
  text: string,
  color = '#ffffff',
  scale = 1,
  shadow = true
): Phaser.GameObjects.Image {
  const key = bakeText(scene, text, color, scale, shadow);
  return scene.add.image(cx, y, key).setOrigin(0.5, 0);
}
